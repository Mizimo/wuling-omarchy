"""Resolve themes and generate the files consumed by stock Omarchy."""

from pathlib import Path
import json
import os
import re
import tomllib
from . import Error, ROOT, SCHEMA, paths
from . import settings


def rgb(value):
    if not isinstance(value, str) or not re.fullmatch(r"#[0-9a-fA-F]{6}", value):
        raise Error(f"Expected an RGB colour, got {value!r}")
    return [int(value[i:i + 2], 16) for i in (1, 3, 5)]


def mix(front, back, amount):
    return "#" + "".join(f"{round(a * amount + b * (1 - amount)):02X}" for a, b in zip(rgb(front), rgb(back)))


def contrast(front, back):
    def luminance(value):
        components = [x / 255 for x in rgb(value)]
        return sum((x / 12.92 if x <= .04045 else ((x + .055) / 1.055) ** 2.4) * weight
                   for x, weight in zip(components, (.2126, .7152, .0722)))
    low, high = sorted((luminance(front), luminance(back)))
    return (high + .05) / (low + .05)


def toml(data):
    lines = ["# Generated by WULING; edit tokens or user overrides, not this file."]
    def key_name(key):
        # Omarchy's lightweight colour/style readers accept bare keys, not the
        # quoted-key form that a general TOML parser would also accept.
        if not re.fullmatch(r"[A-Za-z0-9_-]+", key):
            raise Error(f"Unsupported generated TOML key: {key}")
        return key
    def emit(table, name=""):
        if name:
            lines.extend(("", f"[{name}]"))
        for key, value in table.items():
            if not isinstance(value, dict):
                lines.append(f"{key_name(key)} = {json.dumps(value, ensure_ascii=False)}")
        for key, value in table.items():
            if isinstance(value, dict):
                emit(value, (name + "." if name else "") + key_name(key))
    emit(data)
    result = "\n".join(lines) + "\n"
    tomllib.loads(result)
    return result


def active_name():
    path = paths()["current"] / "theme.name"
    return path.read_text().strip() if path.exists() else None


def resolve(name=None, overrides=None):
    source = settings.tokens()
    name = name or active_name()
    definitions = source["themes"]
    known = name in definitions
    spec = definitions[name] if known else {"preset": "field", "palette": "mist"}
    colours = dict(source["palettes"][spec["palette"]])
    origin = f"theme:{name}" if known else "defaults"
    warnings = []
    # A staged wuling.toml also allows a separately installed/renamed theme.
    current = paths()["current"] / "theme"
    if not known and (current / "wuling.toml").is_file():
        try:
            meta = tomllib.loads((current / "wuling.toml").read_text())
            if meta.get("schema_version") == 1 and meta.get("preset") in source["presets"] and meta.get("palette") in source["palettes"]:
                spec = {key: meta[key] for key in ("preset", "palette")}
                colours = dict(source["palettes"][spec["palette"]])
                origin = f"theme:{name}"
                known = True
        except (OSError, ValueError):
            warnings.append("Cannot read active theme's wuling.toml; using its palette with field shapes.")
    if not known:
        palette_path = current / "colors.toml"
        if palette_path.is_file():
            try:
                native = tomllib.loads(palette_path.read_text())
                for native_key, role in source["omarchy_colors"].items():
                    if native_key in native:
                        rgb(native[native_key])
                        colours[role] = native[native_key]
                bg, fg = colours["ink-2"], colours["paper-2"]
                colours.update({"line": mix(fg, bg, .18), "line-soft": mix(fg, bg, .10),
                                "ink-4": mix(fg, bg, .08), "mist-4": mix(fg, bg, .65)})
                colours["fill"] = colours["accent-ink"] = colours["omarchy-accent"]
                colours["on-accent"] = max((bg, fg), key=lambda x: contrast(x, colours["fill"]))
                origin = f"theme:{name or 'current'}:colors.toml"
            except (OSError, ValueError, Error) as exc:
                warnings.append(f"Invalid active palette: {exc}; using MIST colours.")
        else:
            warnings.append("No active palette found; using MIST colours with field shapes.")
    values = dict(source["defaults"])
    origins = {key: "defaults" for key in values}
    if spec["palette"] == "paper":
        values["menu.selected"] = "fill"
        origins["menu.selected"] = origin
    for key, value in (settings.load() if overrides is None else overrides).items():
        values[key] = settings.validate(key, value)
        origins[key] = "overrides.toml"
    def tagged(items, label):
        return {key: {"value": value, "origin": label} for key, value in items.items()}
    language = values["language"]
    if language == "auto":
        native_language = paths()["home"] / ".config/omarchy/language"
        language = native_language.read_text().strip() if native_language.is_file() else os.environ.get("LANG", "en")
    language = language.replace("_", "-")
    language = "zh-TW" if language.startswith(("zh-TW", "zh-HK", "zh-Hant")) else "zh-CN" if language.startswith("zh") else "en"
    return {"schema_version": SCHEMA, "theme": name, "preset": spec["preset"], "palette": spec["palette"] if known else "external", "language": language,
            "settings": {key: {"value": value, "origin": origins[key]} for key, value in values.items()},
            "colors": tagged(colours, origin), "type": tagged(source["type"], "tokens"),
            "geometry": tagged({**source["geometry"], **source["presets"][spec["preset"]]}, f"preset:{spec['preset']}"),
            "motion": tagged(source["motion"], "tokens"), "sound": tagged(source["sound"], "tokens"), "warnings": warnings}


def shell_data(name, overrides=None):
    source = settings.tokens()
    spec = source["themes"][name]
    palette = spec["palette"]
    p = source["palettes"][palette]
    preset = source["presets"][spec["preset"]]
    selected = (overrides or {}).get("menu.selected", "fill" if palette == "paper" else "edge")
    fg, line, mark = p["paper-1"], p["line"], p["accent-ink"]
    scrim = .8 if spec["preset"] == "hud" else (.74 if palette == "paper" else .72)
    def surface(bg, border, alpha=1.0, width=None):
        result = {"background": bg, "background-alpha": alpha, "text": fg, "border": border, "border-alpha": 1.0}
        if width is not None:
            result["border-width"] = width
        return result
    controls = {}
    for state, alpha, border in (("normal", .04, line), ("hover-cursor", .08, line), ("focus", .08, mark), ("selected", .14, fg)):
        controls.update({state + "-color": fg, state + "-fill-alpha": alpha, state + "-border": border,
                         state + "-border-width": 0 if state == "selected" else 1, state + "-border-alpha": 1.0})
    controls.update({"pressed-fill-alpha": .22, "selection-fill-alpha": .35})
    # Selected-row policy is intentionally centralised; callers never patch TOML.
    selection_bg = p["fill"] if palette == "paper" and selected == "fill" else p["ink-5"]
    selection_border = "0 0 0 2" if selected == "edge" else "0"
    return {
        "bar": {"background": p["ink-2"], "background-alpha": 1.0, "text": fg, "active": p["vermilion"],
                "scale-with-font": True, "size-horizontal": preset["bar_height"], "size-vertical": preset["bar_height"] + 2},
        "hyprland": {"active-border": p["active-border"], "active-border-foreground": line},
        "controls": controls, "spacing": {"scale": 1.0, "scale-with-font": True}, "font": {"base-size": 12},
        "popups": surface(p["ink-2"], p[preset["panel_border"]], width=1),
        "tooltip": surface(p["ink-3"], line, .97),
        "notifications": {**surface(p["ink-3"], p[preset["panel_border"]], width=1), "countdown": mark},
        "menu": {**surface(p["ink-2"], line), "scrim": p["ink-0"], "scrim-alpha": scrim,
                 "selected-background": selection_bg, "selected-background-alpha": 1.0, "selected-text": p["paper-0"],
                 "selected-border": mark, "selected-border-alpha": 1.0, "selected-border-width": selection_border},
        "polkit": {**surface(p["ink-2"], p["active-border"]), "text-error": p["ansi-bright-red"], "border-error": p["vermilion"],
                   "scrim": p["ink-0"], "scrim-alpha": scrim, "accent": mark},
        "lock": {**surface(p["ink-1"], line, .88), "placeholder": p["mist-5"], "text-error": p["ansi-bright-red"],
                 "border-active": p["active-border"], "border-error": p["vermilion"], "selection": mark, "selection-alpha": .35},
        "image-picker": {"scrim": p["ink-0"], "scrim-alpha": scrim, "text": fg, "selected-border": p["active-border"],
                         "selected-border-alpha": 1.0, "unselected-border": fg, "unselected-border-alpha": .28},
    }


def generated_text(name, overrides=None):
    source = settings.tokens()
    spec = source["themes"][name]
    p = source["palettes"][spec["palette"]]
    colours = {"mode": "light" if spec["palette"] == "paper" else "dark"}
    colours.update({key: p[role] for key, role in source["omarchy_colors"].items()})
    result = {"colors.toml": toml(colours), "shell.toml": toml(shell_data(name, overrides)),
              "icons.theme": "Yaru-olive\n" if spec["palette"] == "paper" else "Yaru-yellow\n",
              "wuling.toml": toml({"schema_version": SCHEMA, **spec})}
    if spec["palette"] == "paper":
        result["light.mode"] = ""
    return result
